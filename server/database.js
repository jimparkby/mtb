// Слой БД: один асинхронный интерфейс для SQLite (локально, тесты, Railway volume)
// и PostgreSQL (DATABASE_URL). Запросы пишутся с плейсхолдерами `?`.
//   all(sql, params)   -> строки
//   get(sql, params)   -> первая строка или undefined
//   run(sql, params)   -> { changes }
//   insert(sql, params) -> id новой строки
//   tx(async (t) => …) -> транзакция; t умеет то же самое и lockUser(id)
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import pg from 'pg';

// COUNT/SUM в Postgres приходят строками (bigint/numeric) — для наших сумм хватает Number
pg.types.setTypeParser(20, Number);
pg.types.setTypeParser(1700, Number);

const PK = {
  sqlite: 'INTEGER PRIMARY KEY',
  postgres: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
};

