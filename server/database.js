async function migrate(db) {
  await db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)');
  const done = new Set((await db.all('SELECT version FROM schema_migrations')).map((r) => r.version));
  for (const [i, sql] of MIGRATIONS.entries()) {
    const version = i + 1;
    if (done.has(version)) continue;
    await db.tx(async (t) => {
      await t.exec(sql.replaceAll('{{pk}}', PK[db.dialect]));
      await t.run('INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)', [version, new Date().toISOString()]);
    });
  }
}

function openSqlite(path) {
  if (path !== ':memory:') mkdirSync(dirname(path), { recursive: true });
  const raw = new DatabaseSync(path);
  raw.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;');
  const stmts = new Map();
  const prep = (sql) => {
    let s = stmts.get(sql);
    if (!s) { s = raw.prepare(sql); stmts.set(sql, s); }
    return s;
  };
  const ops = {
    exec: async (sql) => { raw.exec(sql); },
    all: async (sql, p = []) => prep(sql).all(...p),
    get: async (sql, p = []) => prep(sql).get(...p),
    run: async (sql, p = []) => ({ changes: Number(prep(sql).run(...p).changes) }),
    insert: async (sql, p = []) => Number(prep(sql + ' RETURNING id').get(...p).id),
    lockUser: async () => {}, // BEGIN IMMEDIATE уже сериализует запись
  };

  // Соединение одно: пока идёт транзакция, остальные запросы ждут её конца,
  // иначе чужой запрос попал бы внутрь нашей транзакции между await.
  let gate = Promise.resolve();
  const outside = (fn) => async (...a) => { await gate; return fn(...a); };
  async function tx(fn) {
    let release;
    const prev = gate;
    gate = new Promise((r) => { release = r; });
    await prev;
    raw.exec('BEGIN IMMEDIATE');
    try {
      const out = await fn(ops);
      raw.exec('COMMIT');
      return out;
    } catch (err) {
      raw.exec('ROLLBACK');
      throw err;
    } finally {
      release();
    }
  }

  return {
    dialect: 'sqlite',
    exec: outside(ops.exec), all: outside(ops.all), get: outside(ops.get),
    run: outside(ops.run), insert: outside(ops.insert),
    tx, close: async () => raw.close(),
  };
}

function openPostgres(url, { ssl, max = 10 } = {}) {
  const pool = new pg.Pool({ connectionString: url, ssl, max });
  const num = (sql) => { let i = 0; return sql.replace(/\?/g, () => `$${++i}`); };
  const on = (q) => ({
    exec: async (sql) => { await q.query(sql); },
    all: async (sql, p = []) => (await q.query(num(sql), p)).rows,
    get: async (sql, p = []) => (await q.query(num(sql), p)).rows[0],
    run: async (sql, p = []) => ({ changes: (await q.query(num(sql), p)).rowCount }),
    insert: async (sql, p = []) => Number((await q.query(num(sql) + ' RETURNING id', p)).rows[0].id),
    // Покупки и оплаты одного пользователя идут строго по очереди
    lockUser: async (id) => { await q.query('SELECT id FROM users WHERE id = $1 FOR UPDATE', [id]); },
  });
  async function tx(fn) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const out = await fn(on(client));
      await client.query('COMMIT');
      return out;
    } catch (err) {
      await client.query('ROLLBACK').catch(() => {});
      throw err;
    } finally {
      client.release();
    }
  }
  return { dialect: 'postgres', ...on(pool), tx, close: () => pool.end() };
}

// url: postgres://… → PostgreSQL, иначе путь к файлу SQLite (или ':memory:')
export async function openDatabase(target, opts) {
  const db = /^postgres(ql)?:\/\//.test(target) ? openPostgres(target, opts) : openSqlite(target);
  await migrate(db);
  return db;
}
